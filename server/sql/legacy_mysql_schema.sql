CREATE DATABASE IF NOT EXISTS skilltrack CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE skilltrack;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('student','instructor','admin') NOT NULL DEFAULT 'student',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS courses (
 id INT AUTO_INCREMENT PRIMARY KEY, instructor_id INT NOT NULL, title VARCHAR(180) NOT NULL,
 description TEXT NOT NULL, category VARCHAR(80) NOT NULL DEFAULT 'General',
  level ENUM('Beginner','Intermediate','Advanced') NOT NULL DEFAULT 'Beginner',
 published BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(instructor_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS lessons (
 id INT AUTO_INCREMENT PRIMARY KEY, course_id INT NOT NULL, title VARCHAR(180) NOT NULL,
 content LONGTEXT NOT NULL, video_url VARCHAR(600) NULL, position INT NOT NULL DEFAULT 0,
 FOREIGN KEY(course_id) REFERENCES courses(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS enrollments (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, course_id INT NOT NULL,
 enrolled_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY unique_enrollment(user_id,course_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(course_id) REFERENCES courses(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS lesson_progress (
 user_id INT NOT NULL, lesson_id INT NOT NULL, completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,lesson_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(lesson_id) REFERENCES lessons(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS quizzes (
 id INT AUTO_INCREMENT PRIMARY KEY, course_id INT NOT NULL UNIQUE, title VARCHAR(180) NOT NULL,
 pass_percentage INT NOT NULL DEFAULT 70,
 FOREIGN KEY(course_id) REFERENCES courses(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS questions (
 id INT AUTO_INCREMENT PRIMARY KEY, quiz_id INT NOT NULL, prompt TEXT NOT NULL,
 option_a VARCHAR(500) NOT NULL, option_b VARCHAR(500) NOT NULL,
 option_c VARCHAR(500) NOT NULL, option_d VARCHAR(500) NOT NULL,
 correct_option ENUM('A','B','C','D') NOT NULL,
 FOREIGN KEY(quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS quiz_attempts (
 id INT AUTO_INCREMENT PRIMARY KEY, quiz_id INT NOT NULL, user_id INT NOT NULL,
 score INT NOT NULL, total INT NOT NULL, percentage INT NOT NULL,
 answers_json JSON NOT NULL, submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
