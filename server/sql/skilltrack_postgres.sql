CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'student' CHECK (role IN ('student','instructor','admin')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS courses (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 instructor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 title VARCHAR(180) NOT NULL, description TEXT NOT NULL,
 category VARCHAR(80) NOT NULL DEFAULT 'General',
 level VARCHAR(20) NOT NULL DEFAULT 'Beginner' CHECK (level IN ('Beginner','Intermediate','Advanced')),
 published BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS lessons (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
 title VARCHAR(180) NOT NULL, content TEXT NOT NULL,
 video_url VARCHAR(600), position INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS enrollments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
 enrolled_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(user_id,course_id)
);
CREATE TABLE IF NOT EXISTS lesson_progress (
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 lesson_id INTEGER NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
 completed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 PRIMARY KEY(user_id,lesson_id)
);
CREATE TABLE IF NOT EXISTS quizzes (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id INTEGER NOT NULL UNIQUE REFERENCES courses(id) ON DELETE CASCADE,
 title VARCHAR(180) NOT NULL,
 pass_percentage INTEGER NOT NULL DEFAULT 70 CHECK (pass_percentage BETWEEN 0 AND 100)
);
CREATE TABLE IF NOT EXISTS questions (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 quiz_id INTEGER NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
 prompt TEXT NOT NULL,
 option_a VARCHAR(500) NOT NULL, option_b VARCHAR(500) NOT NULL,
 option_c VARCHAR(500) NOT NULL, option_d VARCHAR(500) NOT NULL,
 correct_option CHAR(1) NOT NULL CHECK (correct_option IN ('A','B','C','D'))
);
CREATE TABLE IF NOT EXISTS quiz_attempts (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 quiz_id INTEGER NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 score INTEGER NOT NULL, total INTEGER NOT NULL,
 percentage INTEGER NOT NULL,
 answers_json JSONB NOT NULL,
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_enrollments_course ON enrollments(course_id);
CREATE INDEX IF NOT EXISTS idx_lessons_course ON lessons(course_id);
CREATE INDEX IF NOT EXISTS idx_progress_lesson ON lesson_progress(lesson_id);
CREATE INDEX IF NOT EXISTS idx_attempts_quiz_user ON quiz_attempts(quiz_id,user_id);
